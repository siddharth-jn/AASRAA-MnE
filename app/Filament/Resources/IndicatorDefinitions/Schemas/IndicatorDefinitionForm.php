<?php

namespace App\Filament\Resources\IndicatorDefinitions\Schemas;

use App\Models\IndicatorDefinition;
use App\Services\IndicatorService;
use App\Services\TargetService;
use Carbon\CarbonImmutable;
use DateTimeInterface;
use Filament\Forms\Components\CheckboxList;
use Filament\Forms\Components\DatePicker;
use Filament\Forms\Components\Hidden;
use Filament\Forms\Components\Placeholder;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TagsInput;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Components\Utilities\Get;
use Filament\Schemas\Components\Utilities\Set;
use Filament\Schemas\Components\Wizard;
use Filament\Schemas\Components\Wizard\Step;
use Filament\Schemas\Schema;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Support\Str;

class IndicatorDefinitionForm
{
    public static function configure(Schema $schema, int|string|null $projectId = null): Schema
    {
        $dataTypes = collect(config('impact.data_types'))
            ->mapWithKeys(fn (string $type): array => [$type => Str::headline($type)])
            ->all();
        $targetableDataTypes = app(TargetService::class)->supportedDataTypes();
        $configurationIsLocked = fn (?IndicatorDefinition $record): bool => $record?->hasHistoricalData() ?? false;
        $configurationIsEditable = fn (?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false);
        $isExistingRecord = fn (?IndicatorDefinition $record): bool => $record !== null;

        return $schema->components([
            Wizard::make([
                Step::make('Basic details')
                    ->description('Name and classify the indicator.')
                    ->schema([
                        Placeholder::make('historical_configuration_notice')
                            ->label('Review mode')
                            ->content('Excel import and manual creation save the same indicator configuration. This indicator now has targets or entries, so its reporting setup is shown as a read-only summary to protect historical reports. You can still edit the name, description, monitoring reference, and active status. Use “Create replacement” for a structural change from a new month.')
                            ->visible($configurationIsLocked)
                            ->columnSpanFull(),
                        $projectId === null
                            ? Select::make('project_id')
                                ->label('Programme')
                                ->relationship('project', 'name')
                                ->live()
                                ->visible(fn (?IndicatorDefinition $record): bool => $record === null)
                                ->required()
                            : Hidden::make('project_id')
                                ->default($projectId),
                        Placeholder::make('programme_readonly')
                            ->label('Programme')
                            ->content(fn (?IndicatorDefinition $record): string => $record?->project?->name ?? 'Not set')
                            ->visible($isExistingRecord),
                        TextInput::make('code')
                            ->helperText('A permanent unique code, for example SS-LIT-SESSIONS.')
                            ->visible(fn (?IndicatorDefinition $record): bool => $record === null)
                            ->required()
                            ->maxLength(100)
                            ->unique(ignoreRecord: true),
                        Placeholder::make('code_readonly')
                            ->label('Permanent code')
                            ->content(fn (?IndicatorDefinition $record): string => $record?->code ?? 'Not set')
                            ->helperText('This identifier is generated by the import or set when the indicator is created, and does not change later.')
                            ->visible($isExistingRecord),
                        TextInput::make('name')
                            ->required()
                            ->maxLength(255),
                        Textarea::make('description')
                            ->required()
                            ->columnSpanFull(),
                        Section::make('Monitoring framework reference')
                            ->description('Optional source details retained with the indicator for future review and matching.')
                            ->collapsed()
                            ->schema([
                                Textarea::make('objective')
                                    ->rows(2)
                                    ->columnSpanFull(),
                                Textarea::make('data_collection_method')
                                    ->label('Data collection method')
                                    ->rows(2),
                                TextInput::make('data_collection_frequency')
                                    ->label('Data collection frequency')
                                    ->helperText('Reference information only. Website reporting remains monthly.'),
                                Textarea::make('responsible_persons')
                                    ->label('Responsible persons')
                                    ->rows(2),
                                Textarea::make('data_sources')
                                    ->label('Data sources')
                                    ->rows(2),
                            ])
                            ->columns(2)
                            ->columnSpanFull(),
                        Select::make('category')
                            ->options(array_combine(config('impact.categories'), config('impact.categories')))
                            ->visible($configurationIsEditable)
                            ->required(),
                        TextInput::make('unit')
                            ->placeholder('people, sessions, %, status')
                            ->visible($configurationIsEditable)
                            ->required(),
                        Hidden::make('frequency')->default('monthly'),
                        Placeholder::make('reporting_frequency')
                            ->label('Reporting frequency')
                            ->content('Monthly')
                            ->helperText('Quarterly, half-yearly, and annual reports are calculated from monthly results and targets.'),
                        Select::make('reporting_scope')
                            ->label('Reporting level')
                            ->options([
                                'project' => 'Project level',
                                'programme' => 'Programme level',
                            ])
                            ->default('project')
                            ->live()
                            ->visible($configurationIsEditable)
                            ->required(),
                        TextInput::make('effective_date')
                            ->label('Reporting starts from')
                            ->type('month')
                            ->default(fn (): string => now()->format('Y-m'))
                            ->formatStateUsing(fn (mixed $state): ?string => filled($state)
                                ? ($state instanceof DateTimeInterface ? $state->format('Y-m') : substr((string) $state, 0, 7))
                                : null)
                            ->dehydrateStateUsing(fn (mixed $state): ?string => filled($state) ? CarbonImmutable::createFromFormat('Y-m', $state)->startOfMonth()->toDateString() : null)
                            ->rules(['date_format:Y-m'])
                            ->helperText('The first month for which a target can be set and an achievement can be reported.')
                            ->visible($configurationIsEditable)
                            ->required(),
                        Placeholder::make('locked_basic_configuration')
                            ->label('Saved reporting setup')
                            ->content(fn (?IndicatorDefinition $record): string => self::basicConfigurationSummary($record))
                            ->visible($configurationIsLocked)
                            ->columnSpanFull(),
                    ])
                    ->columns(2),
                Step::make('Input and validation')
                    ->description('Control the generated reporting field and accepted values.')
                    ->schema([
                        Placeholder::make('locked_input_configuration')
                            ->label('Saved input setup')
                            ->content(fn (?IndicatorDefinition $record): string => self::inputConfigurationSummary($record))
                            ->visible($configurationIsLocked)
                            ->columnSpanFull(),
                        Select::make('data_type')
                            ->options($dataTypes)
                            ->live()
                            ->visible($configurationIsEditable)
                            ->afterStateUpdated(function (mixed $state, Get $get, Set $set) use ($targetableDataTypes): void {
                                $options = app(IndicatorService::class)->acrossProjectOptions((string) $state, (string) $get('calculation_method'));
                                if (! array_key_exists((string) $get('centre_aggregation'), $options)) {
                                    $set('centre_aggregation', array_key_first($options));
                                }
                                if (in_array($state, ['single_select', 'status'], true)) {
                                    $set('time_aggregation', 'STATUS');
                                }
                                if (! in_array($state, $targetableDataTypes, true)) {
                                    $set('target_tracking', false);
                                } else {
                                    $set('target_tracking', true);
                                    if (in_array($state, ['boolean', 'single_select', 'status'], true)) {
                                        $set('direction', 'status');
                                    } elseif ($get('direction') === 'status') {
                                        $set('direction', 'higher');
                                    }
                                }
                            })
                            ->required(),
                        Hidden::make('value_required')->default(true),
                        TextInput::make('min_value')
                            ->label('Minimum numeric value')
                            ->numeric()
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && in_array($get('data_type'), ['integer', 'decimal', 'percentage', 'ratio', 'calculated'], true)),
                        TextInput::make('max_value')
                            ->label('Maximum numeric value')
                            ->numeric()
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && in_array($get('data_type'), ['integer', 'decimal', 'percentage', 'ratio', 'calculated'], true)),
                        TextInput::make('precision')
                            ->label('Decimal places')
                            ->numeric()
                            ->minValue(0)
                            ->maxValue(4)
                            ->default(2)
                            ->required()
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && in_array($get('data_type'), ['decimal', 'percentage', 'ratio', 'calculated'], true)),
                        TextInput::make('max_length')
                            ->numeric()
                            ->minValue(1)
                            ->default(2000)
                            ->required()
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && in_array($get('data_type'), ['text', 'long_text'], true)),
                        DatePicker::make('minimum_date')
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && $get('data_type') === 'date'),
                        DatePicker::make('maximum_date')
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && $get('data_type') === 'date'),
                        TagsInput::make('options')
                            ->label('Accepted options')
                            ->helperText('Press Enter after each option. These values generate the reporting dropdown.')
                            ->required(fn (Get $get): bool => in_array($get('data_type'), ['single_select', 'multi_select', 'status'], true))
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && in_array($get('data_type'), ['single_select', 'multi_select', 'status'], true))
                            ->columnSpanFull(),
                        Select::make('calculation_method')
                            ->options([
                                'direct_percentage' => 'Enter the percentage directly',
                                'ratio_percentage' => 'Calculate from numerator ÷ denominator × 100',
                            ])
                            ->default('direct_percentage')
                            ->live()
                            ->required(fn (Get $get): bool => in_array($get('data_type'), ['percentage', 'ratio', 'calculated'], true))
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && in_array($get('data_type'), ['percentage', 'ratio', 'calculated'], true)),
                        TextInput::make('numerator_label')
                            ->placeholder('Students passed')
                            ->required(fn (Get $get): bool => in_array($get('data_type'), ['ratio', 'calculated'], true) || $get('calculation_method') === 'ratio_percentage')
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && (in_array($get('data_type'), ['ratio', 'calculated'], true) || $get('calculation_method') === 'ratio_percentage')),
                        TextInput::make('denominator_label')
                            ->placeholder('Students assessed')
                            ->required(fn (Get $get): bool => in_array($get('data_type'), ['ratio', 'calculated'], true) || $get('calculation_method') === 'ratio_percentage')
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && (in_array($get('data_type'), ['ratio', 'calculated'], true) || $get('calculation_method') === 'ratio_percentage')),
                    ])
                    ->columns(2),
                Step::make('Reporting assignment')
                    ->description('Review who must report this indicator.')
                    ->schema([
                        CheckboxList::make('centres')
                            ->label('Projects')
                            ->relationship(
                                'centres',
                                'name',
                                modifyQueryUsing: function (Builder $query, Get $get, ?IndicatorDefinition $record) use ($projectId): Builder {
                                    $selectedProjectId = $projectId ?? $get('project_id') ?? $record?->project_id;

                                    return $query
                                        ->when($selectedProjectId, fn (Builder $centreQuery): Builder => $centreQuery->whereHas('projects', fn (Builder $projectQuery): Builder => $projectQuery->whereKey($selectedProjectId)))
                                        ->orderBy('name');
                                },
                            )
                            ->searchable()
                            ->bulkToggleable()
                            ->columns(2)
                            ->live()
                            ->afterStateHydrated(fn (mixed $state, Set $set): mixed => $set('target_centre_ids', array_values($state ?? [])))
                            ->afterStateUpdated(fn (mixed $state, Set $set): mixed => $set('target_centre_ids', array_values($state ?? [])))
                            ->required(fn (Get $get): bool => $get('reporting_scope') !== 'programme')
                            ->minItems(fn (Get $get): int => $get('reporting_scope') === 'programme' ? 0 : 1)
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && $get('reporting_scope') !== 'programme')
                            ->helperText('Only projects already assigned to the selected programme are available. Programme-level indicators create one reporting obligation for the whole programme.')
                            ->columnSpanFull(),
                        Placeholder::make('locked_project_assignments')
                            ->label('Assigned projects')
                            ->content(fn (?IndicatorDefinition $record): string => self::assignmentSummary($record))
                            ->visible(fn (?IndicatorDefinition $record): bool => ($record?->hasHistoricalData() ?? false)
                                && ! $record->isProgrammeScoped())
                            ->columnSpanFull(),
                        Placeholder::make('programme_reporting_assignment')
                            ->label('Programme-level reporting')
                            ->content('This indicator is reported once for the whole programme, so it does not have individual project assignments. Return to Basic details and choose Project level if each project should report it separately.')
                            ->visible(fn (Get $get): bool => $get('reporting_scope') === 'programme')
                            ->columnSpanFull(),
                        Hidden::make('target_centre_ids'),
                    ]),
                Step::make('Aggregation')
                    ->description('Define how values combine across time and projects, and whether performance is compared with targets.')
                    ->schema([
                        Placeholder::make('locked_aggregation_configuration')
                            ->label('Saved calculation setup')
                            ->content(fn (?IndicatorDefinition $record): string => self::aggregationConfigurationSummary($record))
                            ->visible($configurationIsLocked)
                            ->columnSpanFull(),
                        Select::make('time_aggregation')
                            ->label('Across months')
                            ->options(fn (Get $get): array => app(IndicatorService::class)->timeAggregationOptions((string) $get('data_type'), (string) $get('calculation_method')))
                            ->helperText(fn (Get $get): string => $get('time_aggregation') === 'UNIQUE COUNT'
                                ? 'Enter the cumulative number of unique beneficiaries reached by the end of each month. Reports use the latest month, so the same person is not added repeatedly. Configure this at programme level when projects may serve the same people.'
                                : 'Defines how monthly approved values become quarterly, half-yearly, and annual results.')
                            ->visible($configurationIsEditable)
                            ->required(),
                        Select::make('centre_aggregation')
                            ->label('Across projects')
                            ->options(fn (Get $get): array => $get('reporting_scope') === 'programme'
                                ? ['NON-AGGREGATABLE' => 'Not applicable at programme level']
                                : app(IndicatorService::class)->acrossProjectOptions((string) $get('data_type'), (string) $get('calculation_method')))
                            ->afterStateUpdated(function (mixed $state, Set $set): void {
                                if ($state === 'STATUS') {
                                    $set('time_aggregation', 'STATUS');
                                }
                            })
                            ->helperText('Used only for project-level indicators when All projects is selected. Each project is first calculated using the time method.')
                            ->visible($configurationIsEditable)
                            ->required(),
                        Hidden::make('target_tracking')->default(true),
                        Placeholder::make('target_rule')
                            ->label('Monthly target rule')
                            ->content('Target required to open data entry')
                            ->helperText('A monthly target, including zero, creates that month’s reporting obligation. A blank target means N/A and no entry is available.')
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && in_array($get('data_type'), $targetableDataTypes, true)),
                        Select::make('direction')
                            ->options(fn (Get $get): array => in_array($get('data_type'), ['boolean', 'single_select', 'status'], true)
                                ? ['status' => 'Match the expected value']
                                : [
                                    'higher' => 'Higher is better',
                                    'lower' => 'Lower is better',
                                    'range' => 'Stay within a target range',
                                ])
                            ->required(fn (Get $get): bool => (bool) $get('target_tracking'))
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && (bool) $get('target_tracking'))
                            ->default('higher'),
                    ])
                    ->columns(2),
                Step::make('Evidence and approval')
                    ->description('Choose whether evidence and approval are required. File limits can be adjusted if needed.')
                    ->schema([
                        Placeholder::make('locked_evidence_configuration')
                            ->label('Saved evidence and approval setup')
                            ->content(fn (?IndicatorDefinition $record): string => self::evidenceConfigurationSummary($record))
                            ->visible($configurationIsLocked)
                            ->columnSpanFull(),
                        Toggle::make('evidence_required')
                            ->live()
                            ->visible($configurationIsEditable)
                            ->afterStateHydrated(function (bool $state, Get $get, Set $set): void {
                                if ($state && (int) $get('min_files') < 1) {
                                    $set('min_files', 1);
                                }
                            })
                            ->afterStateUpdated(function (bool $state, Set $set): void {
                                $set('min_files', $state ? 1 : 0);
                            })
                            ->default(true),
                        Toggle::make('approval_required')
                            ->label('Require approval before results become official')
                            ->visible($configurationIsEditable)
                            ->default(true),
                        Section::make('Advanced evidence limits')
                            ->description('Defaults allow up to five files of 5 MB each; one file is required when evidence is on.')
                            ->collapsed()
                            ->visible(fn (Get $get, ?IndicatorDefinition $record): bool => ! ($record?->hasHistoricalData() ?? false)
                                && (bool) $get('evidence_required'))
                            ->schema([
                                Select::make('allowed_extensions')
                                    ->multiple()
                                    ->options(fn (): array => collect(config('impact.evidence_extensions'))->mapWithKeys(fn (string $extension): array => [$extension => strtoupper($extension)])->all())
                                    ->default(fn (): array => config('impact.evidence_extensions'))
                                    ->formatStateUsing(fn (mixed $state): array => filled($state) ? (array) $state : config('impact.evidence_extensions'))
                                    ->required(),
                                TextInput::make('max_file_kb')
                                    ->label('Maximum file size (KB)')
                                    ->numeric()
                                    ->minValue(1)
                                    ->default(5120)
                                    ->required(),
                                TextInput::make('min_files')
                                    ->label('Minimum files')
                                    ->numeric()
                                    ->minValue(1)
                                    ->maxValue(20)
                                    ->default(1)
                                    ->required(),
                                TextInput::make('max_files')
                                    ->label('Maximum files')
                                    ->numeric()
                                    ->minValue(1)
                                    ->maxValue(20)
                                    ->default(5)
                                    ->required(),
                            ])
                            ->columns(2)
                            ->columnSpanFull(),
                        Toggle::make('active')
                            ->helperText(fn (?IndicatorDefinition $record): string => $record?->hasHistoricalData()
                                ? 'Turn this off to archive the original. Existing targets, entries, evidence, and reports remain attached to it.'
                                : 'Turn this off to archive the definition while keeping its history.')
                            ->default(true),
                    ])
                    ->columns(2),
            ])->columnSpanFull(),
        ]);
    }

    private static function basicConfigurationSummary(?IndicatorDefinition $record): string
    {
        if ($record === null) {
            return 'No reporting setup has been saved.';
        }

        return implode(' · ', [
            'Category: '.$record->category,
            'Unit: '.$record->unit,
            'Reporting level: '.($record->isProgrammeScoped() ? 'Programme level' : 'Project level'),
            'Starts: '.($record->effective_date?->format('M Y') ?? 'Not set'),
            'Frequency: Monthly',
        ]);
    }

    private static function inputConfigurationSummary(?IndicatorDefinition $record): string
    {
        if ($record === null) {
            return 'No input setup has been saved.';
        }

        $summary = ['Input type: '.Str::headline($record->data_type)];

        if ($record->data_type === 'integer') {
            $summary[] = 'Whole numbers only';
        } elseif (in_array($record->data_type, ['decimal', 'percentage', 'ratio', 'calculated'], true)) {
            $summary[] = 'Decimal places: '.($record->precision ?? 2);
        }

        if (in_array($record->data_type, ['integer', 'decimal', 'percentage', 'ratio', 'calculated'], true)) {
            $summary[] = self::numericLimitsSummary($record);
        }

        if (in_array($record->data_type, ['text', 'long_text'], true)) {
            $summary[] = 'Maximum length: '.($record->max_length ?? 2000).' characters';
        }

        if ($record->data_type === 'date') {
            $summary[] = self::dateLimitsSummary($record);
        }

        if (in_array($record->data_type, ['single_select', 'multi_select', 'status'], true)) {
            $options = collect($record->options ?? [])->filter()->implode(', ');
            $summary[] = 'Accepted options: '.($options !== '' ? $options : 'None saved');
        }

        if (in_array($record->data_type, ['percentage', 'ratio', 'calculated'], true)) {
            $summary[] = $record->calculation_method === 'ratio_percentage'
                ? 'Calculation: numerator divided by denominator, multiplied by 100'
                : 'Calculation: percentage entered directly';
        }

        if ($record->calculation_method === 'ratio_percentage') {
            $summary[] = 'Numerator: '.($record->numerator_label ?: 'Numerator');
            $summary[] = 'Denominator: '.($record->denominator_label ?: 'Denominator');
        }

        return implode(' · ', $summary);
    }

    private static function numericLimitsSummary(IndicatorDefinition $record): string
    {
        if ($record->min_value === null && $record->max_value === null) {
            return 'No minimum or maximum limit';
        }

        if ($record->min_value === null) {
            return 'Maximum: '.$record->max_value;
        }

        if ($record->max_value === null) {
            return 'Minimum: '.$record->min_value;
        }

        return 'Allowed range: '.$record->min_value.' to '.$record->max_value;
    }

    private static function dateLimitsSummary(IndicatorDefinition $record): string
    {
        if ($record->minimum_date === null && $record->maximum_date === null) {
            return 'No minimum or maximum date';
        }

        if ($record->minimum_date === null) {
            return 'Latest accepted date: '.$record->maximum_date->format('d M Y');
        }

        if ($record->maximum_date === null) {
            return 'Earliest accepted date: '.$record->minimum_date->format('d M Y');
        }

        return 'Accepted dates: '.$record->minimum_date->format('d M Y').' to '.$record->maximum_date->format('d M Y');
    }

    private static function assignmentSummary(?IndicatorDefinition $record): string
    {
        if ($record === null) {
            return 'No project assignment has been saved.';
        }

        $projects = $record->centres()->orderBy('name')->pluck('name')->implode(', ');

        return $projects !== '' ? $projects : 'No project assignment has been saved.';
    }

    private static function aggregationConfigurationSummary(?IndicatorDefinition $record): string
    {
        if ($record === null) {
            return 'No calculation setup has been saved.';
        }

        $indicatorService = app(IndicatorService::class);
        $timeOptions = $indicatorService->timeAggregationOptions($record->data_type, $record->calculation_method);
        $projectOptions = $record->isProgrammeScoped()
            ? ['NON-AGGREGATABLE' => 'Not applicable at programme level']
            : $indicatorService->acrossProjectOptions($record->data_type, $record->calculation_method);
        $directionOptions = [
            'higher' => 'Higher is better',
            'lower' => 'Lower is better',
            'range' => 'Stay within a target range',
            'status' => 'Match the expected value',
        ];
        $summary = [
            'Across months: '.($timeOptions[$record->time_aggregation] ?? Str::headline((string) $record->time_aggregation)),
            'Across projects: '.($projectOptions[$record->centre_aggregation] ?? Str::headline((string) $record->centre_aggregation)),
        ];

        if ($record->target_tracking) {
            $summary[] = 'Target rule: monthly target required to open data entry';
            $summary[] = 'Performance: '.($directionOptions[$record->direction] ?? Str::headline((string) $record->direction));
        } else {
            $summary[] = 'Target tracking: not used for this input type';
        }

        return implode(' · ', $summary);
    }

    private static function evidenceConfigurationSummary(?IndicatorDefinition $record): string
    {
        if ($record === null) {
            return 'No evidence setup has been saved.';
        }

        $summary = [
            'Evidence required: '.($record->evidence_required ? 'Yes' : 'No'),
            'Approval required: '.($record->approval_required ? 'Yes' : 'No'),
        ];

        if ($record->evidence_required) {
            $extensions = collect($record->allowed_extensions ?? [])->map(fn (string $extension): string => strtoupper($extension))->implode(', ');
            $summary[] = 'Files: '.$record->min_files.' to '.$record->max_files;
            $summary[] = 'Maximum size: '.self::formatFileSize((int) $record->max_file_kb);
            $summary[] = 'Allowed types: '.($extensions !== '' ? $extensions : 'None saved');
        }

        return implode(' · ', $summary);
    }

    private static function formatFileSize(int $kilobytes): string
    {
        if ($kilobytes >= 1024 && $kilobytes % 1024 === 0) {
            return ($kilobytes / 1024).' MB per file';
        }

        return $kilobytes.' KB per file';
    }
}
